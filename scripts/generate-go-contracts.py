#!/usr/bin/env python3
"""Generate validation rules from the pinned canonical latr-packages dependency."""
import json
import pathlib
import subprocess
import sys

root = pathlib.Path(__file__).resolve().parent.parent
source = root / "node_modules/latr-packages/packages/lexicons"
output = root / "services/go-backend/internal/gateway/contracts_gen.go"
lines = ["// Code generated by scripts/generate-go-contracts.py; DO NOT EDIT.",
         "package gateway", "", "var contracts = map[string]contract{"]
for path in sorted(source.glob("*.json")):
    doc = json.loads(path.read_text())
    main = doc.get("defs", {}).get("main", {})
    if main.get("type") not in ("query", "procedure") or any(part in doc["id"] for part in (".developer.", ".saved.")):
        continue
    verb = "GET" if main["type"] == "query" else "POST"
    if doc["id"] == "link.latr.bookmarks.setState":
        verb = "PATCH"  # Existing gateway/client contract.
    schema = main.get("input", {}).get("schema", main.get("parameters", {}))
    lines.append(f'{json.dumps(doc["id"])}: {{Verb: {json.dumps(verb)}, Fields: map[string]field{{')
    for name, rule in sorted(schema.get("properties", {}).items()):
        parts = [f'Kind: {json.dumps(rule["type"])}', f'Required: {str(name in schema.get("required", [])).lower()}']
        for k, go in (("minimum", "Min"), ("maximum", "Max"), ("default", "Default"), ("maxLength", "Length"), ("maxGraphemes", "Graphemes")):
            if k in rule:
                parts.append(f'{go}: {rule[k]}')
        if "enum" in rule:
            parts.append('Enum: []string{' + ','.join(json.dumps(x) for x in rule["enum"]) + '}')
        lines.append(f'{json.dumps(name)}: {{' + ', '.join(parts) + '},')
    if doc["id"] == "link.latr.bookmarks.migrateLegacy":
        lines.append('"upstreamDpopProof": {Kind: "string", Length: 1048576},')
    lines.append('}},')
lines.append('}')
generated = subprocess.run(["gofmt"], input='\n'.join(lines).encode(), stdout=subprocess.PIPE, check=True).stdout
if "--check" in sys.argv:
    if not output.exists() or output.read_bytes() != generated:
        sys.exit("Go contracts differ from canonical latr-packages; regenerate them")
else:
    output.write_bytes(generated)
